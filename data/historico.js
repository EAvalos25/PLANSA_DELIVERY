/**
 * Expande el histórico a solicitudes con la forma que usa el resto de la app
 * (ver db/schema.js). El correlativo se asigna por orden cronológico, así que
 * los tickets nuevos siguen numerando desde el último.
 */
export function historico2026() {
  return SERVICIOS.map(([fecha, lugar, tipo, costo, quien, salida, motivo], i) => {
    const [a, m, d] = fecha.split('-').map(Number);
    // La planilla anota el día, no la hora: se fija una hora de oficina para
    // que el servicio caiga en su fecha en cualquier zona horaria.
    const cuando = new Date(a, m - 1, d, 9, 0, 0).toISOString();
    const p = SOLICITANTES[quien];
    return {
      id: 'REQ-' + String(i + 1).padStart(3, '0'),
      creado: cuando,
      dni: p.dni, nombre: p.nombre, cargo: p.cargo, area: p.area,
      tipo: tipo ? 'Entregar' : 'Recoger',
      servicio: tipo ? 'Envío de documentos o paquete' : 'Recojo de documentos o paquete',
      motivo: motivo,
      origen: salida >= 0 ? 'Otros' : PLANTA,
      origenDetalle: salida >= 0 ? LUGARES[salida] : '',
      destino: LUGARES[lugar],
      contacto: '', telefono: '',
      fechaProg: fecha, horaProg: '',
      vehiculo: null,
      costo: costo,
      estado: 'Concluido',
      // Solo consta el día del servicio: sin hora de salida ni de cierre, los
      // tiempos del flujo quedan fuera del cálculo en vez de valer cero.
      tsEspera: cuando, tsTransito: null, tsConcluido: null,
      fuente: 'historico'
    };
  });
}
