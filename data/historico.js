const hhmm = min => String(Math.floor(min / 60)).padStart(2, '0') + ':' + String(min % 60).padStart(2, '0');

/**
 * Expande el histórico a solicitudes con la forma que usa el resto de la app
 * (ver backend/db/esquema.sql). El correlativo se asigna por orden cronológico,
 * así que los tickets nuevos siguen numerando desde el último.
 */
export function historico2026() {
  return SERVICIOS.map(([fecha, lugar, tipo, costo, quien, salida, motivo, hora], i) => {
    const [a, m, d] = fecha.split('-').map(Number);
    // Con la hora de la planilla el servicio queda a su hora real; sin ella se
    // fija una hora de oficina para que caiga en su fecha en cualquier zona.
    const min = hora >= 0 ? hora : 9 * 60;
    const cuando = new Date(a, m - 1, d, Math.floor(min / 60), min % 60, 0).toISOString();
    const p = SOLICITANTES[quien];
    return {
      id: 'REQ-' + String(i + 1).padStart(3, '0'),
      creado: cuando,
      dni: p.dni, nombre: p.nombre, cargo: p.cargo, area: p.area,
      tipo: tipo ? 'Entregar' : 'Recoger',
      servicio: tipo ? 'Envío de documentos o paquete' : 'Recojo de documentos o paquete',
      motivo: motivo,
      origen: salida >= 0 ? 'Otros' : PLANTA,
      origenDetalle: salida >= 0 ? LUGARES[salida] : '',
      destino: LUGARES[lugar],
      contacto: '', telefono: '',
      fechaProg: fecha, horaProg: hora >= 0 ? hhmm(hora) : '',
      vehiculo: null,
      costo: costo,
      estado: 'Concluido',
      // La hora de salida de la planilla es la grilla de la agenda, no una
      // medición: los tiempos del flujo quedan fuera del cálculo en vez de
      // valer siempre una hora. Ver la nota de cabecera.
      tsEspera: cuando, tsTransito: null, tsConcluido: null,
      fuente: 'historico'
    };
  });
}
